// MediCircle/DiagDesk design tokens — build: JSON (single source) → dist outputs.
// Resolves DTCG aliases, then emits: tokens.css (HSL CSS vars, brand+dark switchable),
// tailwind-preset.js (shadcn-compatible), and theme.ts (React Native / NativeWind).
// Run: `node build/build.mjs` (no deps). Edit tokens/*.json, re-run, every platform updates.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const T = (f) => JSON.parse(readFileSync(join(ROOT, 'tokens', f), 'utf8'));
const core = T('core.json'), semantic = T('semantic.json'), comp = T('components.json');
const brands = { diagdesk: T('brand.diagdesk.json'), medicircle: T('brand.medicircle.json') };

const isObj = (v) => v && typeof v === 'object' && !Array.isArray(v);
function deepMerge(a, b) { const o = { ...a }; for (const k in b) o[k] = isObj(b[k]) && isObj(a?.[k]) ? deepMerge(a[k], b[k]) : b[k]; return o; }
function getPath(tree, path) { return path.split('.').reduce((n, k) => (n ? n[k] : undefined), tree); }
function resolve(val, tree, seen = 0) {
  if (seen > 20) throw new Error('alias cycle');
  if (typeof val === 'string') {
    const m = val.match(/^\{([^}]+)\}$/);
    if (m) { const node = getPath(tree, m[1]); return resolve(isObj(node) ? node.$value : node, tree, seen + 1); }
    return val;
  }
  if (isObj(val)) return resolve(val.$value, tree, seen + 1);
  return val;
}

// hex -> "H S% L%" (shadcn channel format)
function hexToHsl(hex) {
  let h = hex.replace('#', ''); if (h.length === 3) h = h.split('').map(c => c + c).join('');
  const r = parseInt(h.slice(0, 2), 16) / 255, g = parseInt(h.slice(2, 4), 16) / 255, b = parseInt(h.slice(4, 6), 16) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b); let H = 0, S = 0; const L = (max + min) / 2;
  if (max !== min) { const d = max - min; S = L > 0.5 ? d / (2 - max - min) : d / (max + min);
    H = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4; H /= 6; }
  return `${Math.round(H * 360)} ${Math.round(S * 100)}% ${Math.round(L * 100)}%`;
}

// shadcn role order; map internal 'danger' -> 'destructive'
const ROLES = ['background','foreground','card','card-foreground','popover','popover-foreground',
  'primary','primary-foreground','secondary','secondary-foreground','muted','muted-foreground',
  'accent','accent-foreground','destructive','destructive-foreground','border','input','ring',
  'success','success-foreground','warning','warning-foreground'];
const internal = (r) => r === 'destructive' ? 'danger' : r === 'destructive-foreground' ? 'danger-foreground' : r;

function resolvedColors(brandKey, mode) {
  const tree = deepMerge(deepMerge(core, brands[brandKey]), semantic);
  const out = {};
  for (const role of ROLES) { const hex = resolve(semantic.color[mode][internal(role)], tree); if (hex) out[role] = hexToHsl(hex); }
  return out;
}
function resolvedHex(brandKey, mode) {
  const tree = deepMerge(deepMerge(core, brands[brandKey]), semantic);
  const out = {}; for (const role of ROLES) { const hex = resolve(semantic.color[mode][internal(role)], tree); if (hex) out[role] = hex; } return out;
}

const radius = core.radius.md.$value; // shadcn --radius
const cssVars = (obj) => Object.entries(obj).map(([k, v]) => `    --${k}: ${v};`).join('\n');

// ---- tokens.css ----
let css = `/* GENERATED by build/build.mjs — do not edit. Edit tokens/*.json and re-run. */
/* Brand: [data-brand="diagdesk"|"medicircle"] (default diagdesk). Mode: add .dark (or [data-theme="dark"]). */
@import "../fonts/fonts.css";
:root { --font-sans: ${core.font.family.sans.$value.map(f=>/\s/.test(f)?`'${f}'`:f).join(', ')}; --radius: ${radius}; }
`;
for (const b of Object.keys(brands)) {
  const sel = b === 'diagdesk' ? `:root, [data-brand="diagdesk"]` : `[data-brand="medicircle"]`;
  css += `\n${sel} {\n${cssVars(resolvedColors(b, 'light'))}\n  }\n`;
  const darkSel = b === 'diagdesk' ? `:root.dark, [data-brand="diagdesk"].dark, [data-brand="diagdesk"][data-theme="dark"]`
                                   : `[data-brand="medicircle"].dark, [data-brand="medicircle"][data-theme="dark"]`;
  css += `${darkSel} {\n${cssVars(resolvedColors(b, 'dark'))}\n  }\n`;
}
mkdirSync(join(ROOT, 'dist'), { recursive: true });
writeFileSync(join(ROOT, 'dist', 'tokens.css'), css);

// ---- tailwind-preset.js ----
const colorMap = ROLES.reduce((m, r) => { m[r] = `hsl(var(--${r}) / <alpha-value>)`; return m; }, {});
const fontSize = Object.fromEntries(Object.entries(core.fontSize).filter(([k]) => k !== '$type').map(([k, v]) => [k, v.$value]));
const spacing = Object.fromEntries(Object.entries(core.space).filter(([k]) => k !== '$type').map(([k, v]) => [k, v.$value]));
const screens = Object.fromEntries(Object.entries(core.breakpoint).map(([k, v]) => [k, v.$value]));
const shadows = Object.fromEntries(Object.entries(core.shadow).filter(([k]) => k !== '$type').map(([k, v]) => [k, v.$value]));
const preset = `/* GENERATED by build/build.mjs — Tailwind preset. Usage: presets: [require('@medicircle/design-system/dist/tailwind-preset')] */
module.exports = {
  darkMode: ['class', '[data-theme="dark"]'],
  theme: {
    extend: {
      colors: ${JSON.stringify({ ...colorMap, border: 'hsl(var(--border) / <alpha-value>)' }, null, 8)},
      fontFamily: { sans: 'var(--font-sans)'.split(','), icon: ['Material Symbols Outlined'] },
      fontSize: ${JSON.stringify(fontSize, null, 8)},
      spacing: ${JSON.stringify(spacing, null, 8)},
      borderRadius: { sm: '${core.radius.sm.$value}', DEFAULT: 'var(--radius)', md: 'var(--radius)', lg: '${core.radius.lg.$value}', xl: '${core.radius.xl.$value}', full: '${core.radius.full.$value}' },
      boxShadow: ${JSON.stringify(shadows, null, 8)},
      screens: ${JSON.stringify(screens, null, 8)},
    },
  },
};
`;
writeFileSync(join(ROOT, 'dist', 'tailwind-preset.js'), preset);

// ---- theme.ts (React Native / NativeWind) ----
const rn = {
  brands: Object.fromEntries(Object.keys(brands).map(b => [b, { light: resolvedHex(b, 'light'), dark: resolvedHex(b, 'dark') }])),
  spacing, radius: { sm: core.radius.sm.$value, md: core.radius.md.$value, lg: core.radius.lg.$value, xl: core.radius.xl.$value, full: core.radius.full.$value },
  fontSize, fontFamily: { sans: 'Inter', icon: 'Material Symbols Outlined' },
};
writeFileSync(join(ROOT, 'dist', 'theme.ts'),
  `/* GENERATED by build/build.mjs — React Native / NativeWind theme. */\nexport const theme = ${JSON.stringify(rn, null, 2)} as const;\nexport type Brand = keyof typeof theme.brands;\nexport default theme;\n`);

console.log('Built dist/: tokens.css, tailwind-preset.js, theme.ts  (brands: ' + Object.keys(brands).join(', ') + ' × light/dark)');
